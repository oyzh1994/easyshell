    @Test
    public void testComplexMetadataAndJsonValue() {
        List<H2Column> columns = this.client.selectColumns("DEMO_COMPLEX_EDIT");
        Assert.assertEquals(20, columns.size());
        H2Column clob = columns.stream()
                .filter(column -> "LONG_TEXT".equals(column.getName()))
                .findFirst().orElseThrow();
        Assert.assertNull("CLOB metadata must not overflow Integer", clob.getSize());
        H2Column amount = columns.stream()
                .filter(column -> "AMOUNT".equals(column.getName()))
                .findFirst().orElseThrow();
        Assert.assertEquals(Integer.valueOf(14), amount.getSize());
        Assert.assertEquals(Integer.valueOf(2), amount.getDigits());

        List<Map<String, Object>> records = this.client.selectRecords(
                "DEMO_COMPLEX_EDIT", columns, 0, 1);
        Object json = records.getFirst().get("JSON_DATA");
        Assert.assertTrue(json instanceof String);
        Assert.assertTrue(json.toString().contains("priority"));
        Assert.assertTrue(records.getFirst().get("BINARY_DATA") instanceof byte[]);
    }

    @Test
    public void testComplexCsvExportImportAndTableEdit() throws Exception {
        List<H2Column> columns = this.client.selectColumns("DEMO_COMPLEX_EDIT");
        Path csv = this.tempDir.resolve("complex.csv");
        H2DataExportTable exportTable = new H2DataExportTable();
        exportTable.setName("DEMO_COMPLEX_EDIT");
        exportTable.setFilePath(csv.toString());
        exportTable.columns(columns);
        H2DataExportHandler exportHandler = new H2DataExportHandler(
                this.client, "DEMO_COMPLEX_EDIT");
        exportHandler.setFileType("csv");
        exportHandler.includeTitle(true);
        exportHandler.fieldSeparator(",");
        exportHandler.setTables(List.of(exportTable));
        exportHandler.doAction();
        String csvText = Files.readString(csv);
        Assert.assertTrue(csvText.contains("priority"));
        Assert.assertTrue(csvText.contains("X'0102030405'"));

        new H2SchemaManager(this.client).cloneTable(
                "DEMO_COMPLEX_EDIT", "DEMO_COMPLEX_COPY", false);
        H2DataImportFile importFile = new H2DataImportFile();
        importFile.setFile(csv.toFile());
        importFile.setTargetTableName("DEMO_COMPLEX_COPY");
        H2DataImportHandler importHandler = new H2DataImportHandler(
                this.client, "DEMO_COMPLEX_COPY");
        importHandler.setFileType("csv");
        importHandler.importMode("2");
        importHandler.columnIndex(0);
        importHandler.dataRowStarts(1);
        importHandler.fieldSeparator(",");
        importHandler.setFiles(List.of(importFile));
        importHandler.doAction();
        Assert.assertEquals(3, this.client.selectRowCount("DEMO_COMPLEX_COPY"));

        List<H2Column> copiedColumns = this.client.selectColumns("DEMO_COMPLEX_COPY");
        Map<String, Object> copied = this.client.selectRecords(
                "DEMO_COMPLEX_COPY", copiedColumns, 0, 10).stream()
                .filter(record -> "EDIT-001".equals(record.get("CODE")))
                .findFirst().orElseThrow();
        Assert.assertTrue(copied.get("JSON_DATA") instanceof String);
        Assert.assertEquals("Quarterly planning long text.", copied.get("LONG_TEXT"));
        Assert.assertArrayEquals(new byte[]{1, 2, 3, 4, 5}, (byte[]) copied.get("BINARY_DATA"));

        List<H2Column> editColumns = this.client.selectColumns("DEMO_COMPLEX_EDIT");
        H2Column editAmount = editColumns.stream()
                .filter(column -> "AMOUNT".equals(column.getName()))
                .findFirst().orElseThrow();
        editAmount.setSize(16);
        editAmount.setDigits(3);
        H2Column title = editColumns.stream()
                .filter(column -> "TITLE".equals(column.getName()))
                .findFirst().orElseThrow();
        title.setName("HEADLINE");
        H2Column remark = new H2Column("EDIT_REMARK");
        remark.setType("CHARACTER VARYING");
        remark.setSize(200);
        remark.setCreated(true);
        editColumns.add(remark);
        H2Table target = new H2Table("DEMO_COMPLEX_EDIT");
        target.setColumns(editColumns);
        new H2SchemaManager(this.client).updateTable("DEMO_COMPLEX_EDIT", target);
        List<H2Column> updated = this.client.selectColumns("DEMO_COMPLEX_EDIT");
        Assert.assertTrue(updated.stream().anyMatch(column -> "HEADLINE".equals(column.getName())));
        Assert.assertTrue(updated.stream().anyMatch(column -> "EDIT_REMARK".equals(column.getName())));
        H2Column updatedAmount = updated.stream()
                .filter(column -> "AMOUNT".equals(column.getName()))
                .findFirst().orElseThrow();
        Assert.assertEquals(Integer.valueOf(16), updatedAmount.getSize());
        Assert.assertEquals(Integer.valueOf(3), updatedAmount.getDigits());
    }

    @Test
    public void testComplexViewEditAndQueryRecordEdit() {
        H2View view = this.client.selectView("DEMO_V_COMPLEX_DEPARTMENT");
        view.setDefinition("""
                SELECT E.ID, E.CODE, E.TITLE, E.AMOUNT, E.VERSION, D.NAME AS DEPARTMENT_NAME
                FROM DEMO_COMPLEX_EDIT E
                JOIN DEMO_DEPARTMENT D ON D.ID = E.DEPARTMENT_ID
                """);
        new H2SchemaManager(this.client).saveView("DEMO_V_COMPLEX_DEPARTMENT", view);
        Assert.assertTrue(this.client.viewDefinition("DEMO_V_COMPLEX_DEPARTMENT")
                .contains("VERSION"));

        DBQueryResults<H2ExecuteResult> query = this.client.executeSql("""
                SELECT E.ID, E.TITLE, E.AMOUNT, D.NAME AS DEPARTMENT_NAME
                FROM DEMO_COMPLEX_EDIT E
                JOIN DEMO_DEPARTMENT D ON D.ID = E.DEPARTMENT_ID
                WHERE E.ID = 1
                """);
        Assert.assertTrue(query.isSuccess());
        H2ExecuteResult result = query.getResults().getFirst();
        Assert.assertTrue(result.isUpdatable());
        Assert.assertNotNull(result.getPrimaryKey());
        H2Record record = result.getRecords().getFirst();

        H2Column titleColumn = result.getColumns().stream()
                .filter(column -> "TITLE".equals(column.getName()))
                .findFirst().orElseThrow();
        DBRecordData changed = new DBRecordData();
        changed.put(titleColumn, "Edited through query");
        H2RecordPrimaryKey primaryKey = new H2RecordPrimaryKey();
        primaryKey.init(result.getPrimaryKey(), record);
        H2UpdateRecordParam update = new H2UpdateRecordParam();
        update.setTableName(result.tableName());
        update.setPrimaryKey(primaryKey);
        update.setUpdateRecord(changed);
        Assert.assertEquals(1, this.client.updateRecord(update));
        H2ExecuteResult check = this.client.executeSql(
                "SELECT TITLE FROM DEMO_COMPLEX_EDIT WHERE ID = 1")
                .getResults().getFirst();
        Assert.assertEquals("Edited through query",
                check.getRecords().getFirst().getRecordData().value("TITLE"));
    }

    @Test
    public void testInsertNewComplexRecordUsesDatabaseDefaults() {
        List<H2Column> columns = this.client.selectColumns("DEMO_COMPLEX_EDIT");
        DBRecordData data = new DBRecordData();
        for (H2Column column : columns) {
            if ("CODE".equals(column.getName())) {
                data.put(column, "EDIT-NEW");
            } else if ("TITLE".equals(column.getName())) {
                data.put(column, "New default record");
            } else if ("DEPARTMENT_ID".equals(column.getName())) {
                data.put(column, 1L);
            } else {
                data.put(column, null);
            }
        }
        H2InsertRecordParam insert = new H2InsertRecordParam();
        insert.setTableName("DEMO_COMPLEX_EDIT");
        insert.setRecord(data);
        Assert.assertEquals(1, this.client.insertRecord(insert));

        H2ExecuteResult result = this.client.executeSql("""
                SELECT COUNT(*) AS CNT
                FROM DEMO_COMPLEX_EDIT
                WHERE CODE = 'EDIT-NEW'
                  AND CATEGORY = 'GENERAL'
                  AND AMOUNT = 0
                  AND ENABLED = TRUE
                  AND CREATED_AT IS NOT NULL
                  AND TIMEZONE_AT IS NOT NULL
                  AND UUID_DATA IS NOT NULL
                  AND AMOUNT_WITH_TAX = 0
                  AND TITLE_UPPER = 'NEW DEFAULT RECORD'
                """).getResults().getFirst();
        Assert.assertEquals(1L,
                result.getRecords().getFirst().getRecordData().value("CNT"));
    }

    @Test
    public void testUpdateJsonObjectUsesJsonSqlValue() {
        List<H2Column> columns = this.client.selectColumns("DEMO_COMPLEX_EDIT");
        H2Column jsonColumn = columns.stream()
                .filter(column -> "JSON_DATA".equals(column.getName()))
                .findFirst().orElseThrow();
        JSONObject json = new JSONObject();
        json.put("priority", 7);
        json.put("tags", List.of("record-editor"));

        DBRecordData changed = new DBRecordData();
        changed.put(jsonColumn, json);
        H2RecordPrimaryKey primaryKey = new H2RecordPrimaryKey();
        primaryKey.setColumnName("ID");
        primaryKey.setOriginalData(1L);
        H2UpdateRecordParam update = new H2UpdateRecordParam();
        update.setTableName("DEMO_COMPLEX_EDIT");
        update.setPrimaryKey(primaryKey);
        update.setUpdateRecord(changed);

        Assert.assertEquals(1, this.client.updateRecord(update));
        H2ExecuteResult result = this.client.executeSql("""
                SELECT JSON_DATA
                FROM DEMO_COMPLEX_EDIT
                WHERE ID = 1
                """).getResults().getFirst();
        Object value = result.getRecords().getFirst().getRecordData().value("JSON_DATA");
        Assert.assertTrue(value instanceof String);
        JSONObject saved = JSONObject.parseObject(value.toString());
        Assert.assertEquals(7, saved.getIntValue("priority"));
        Assert.assertEquals("record-editor", saved.getJSONArray("tags").getString(0));
    }

    @Test
    public void testTransportComplexTablesAndViews() throws Throwable {
        Path targetFile = this.tempDir.resolve("target");
        ShellH2Client target = new ShellH2Client(this.connect(targetFile));
        target.start(5);
        try {
            H2DataTransportHandler handler = new H2DataTransportHandler();
            handler.setSourceClient(this.client);
            handler.setTargetClient(target);
            List<DBDataTransportObject> tables = new ArrayList<>();
            for (String name : List.of(
                    "DEMO_COMPLEX_EDIT",
                    "DEMO_DEPARTMENT",
                    "DEMO_ASSIGNMENT",
                    "DEMO_PROJECT")) {
                DBDataTransportObject object = new DBDataTransportObject();
                object.setName(name);
                tables.add(object);
            }
            handler.setTables(tables);
            DBDataTransportObject view = new DBDataTransportObject();
            view.setName("DEMO_V_COMPLEX_DEPARTMENT");
            handler.setViews(List.of(view));
            handler.doAction();

            Assert.assertEquals(3, target.selectRowCount("DEMO_COMPLEX_EDIT"));
            Assert.assertEquals(2, target.selectRowCount("DEMO_DEPARTMENT"));
            Assert.assertEquals(2, target.selectRowCount("DEMO_PROJECT"));
            Assert.assertEquals(3, target.selectRowCount("DEMO_ASSIGNMENT"));
            Assert.assertFalse(target.selectForeignKeys(
                    target.defaultDatabaseName(), "DEMO_COMPLEX_EDIT").isEmpty());
            Assert.assertNotNull(target.selectView("DEMO_V_COMPLEX_DEPARTMENT"));
        } finally {
            target.close();
        }
    }
