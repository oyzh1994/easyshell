    private Path tempDir;

    private Path sourceFile;

    private ShellH2Client client;

    @Before
    public void setUp() throws Throwable {
        this.tempDir = Files.createTempDirectory("easyshell-h2-complex-");
        this.sourceFile = this.tempDir.resolve("source");
        this.client = new ShellH2Client(this.connect(this.sourceFile));
        this.client.start(5);
        this.createComplexSchema(this.client);
    }

    @After
    public void tearDown() throws Exception {
        if (this.client != null) {
            this.client.close();
        }
        if (this.tempDir != null && Files.exists(this.tempDir)) {
            Files.walk(this.tempDir).sorted(Comparator.reverseOrder())
                    .forEach(path -> path.toFile().delete());
        }
    }

    private ShellConnect connect(Path file) {
        ShellConnect connect = new ShellConnect();
        connect.setName(file.getFileName().toString());
        connect.setType(ShellPrototype.H2);
        connect.setOsType(ShellPrototype.H2);
        connect.setHost(file.toString());
        connect.setConnectTimeOut(5);
        connect.setEnvironment("urlMode=file\nschema=PUBLIC\ncreateIfMissing=true\n");
        return connect;
    }

