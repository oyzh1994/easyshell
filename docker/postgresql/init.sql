-- PostgreSQL 测试对象
-- 仅在容器首次初始化数据目录时自动执行

CREATE SCHEMA IF NOT EXISTS demo;

-- 表
CREATE TABLE demo.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    email TEXT UNIQUE,
    age INTEGER DEFAULT 18 CHECK (age >= 0),
    balance NUMERIC(12, 2) DEFAULT 0,
    active BOOLEAN DEFAULT TRUE,
    avatar BYTEA,
    profile JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE demo.users IS '用户表';
COMMENT ON COLUMN demo.users.name IS '用户名';
COMMENT ON COLUMN demo.users.email IS '邮箱';
COMMENT ON COLUMN demo.users.profile IS '扩展信息';

CREATE INDEX idx_users_name ON demo.users (name);

INSERT INTO demo.users (name, email, age, balance, active, profile)
VALUES ('alice', 'a@example.com', 20, 10.50, TRUE, '{"level": 1}'),
       ('bob', 'b@example.com', 30, 20.00, FALSE, '{"level": 2}');

-- 视图
CREATE VIEW demo.v_users AS
SELECT id, name, email, age, active
FROM demo.users;

COMMENT ON VIEW demo.v_users IS '用户视图';

-- 序列
CREATE SEQUENCE demo.seq_order
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 999999
    START WITH 1
    CACHE 1
    CYCLE;

COMMENT ON SEQUENCE demo.seq_order IS '订单序列';

-- 函数
CREATE OR REPLACE FUNCTION demo.fn_add(a INTEGER, b INTEGER)
    RETURNS INTEGER
    LANGUAGE plpgsql
AS $$
BEGIN
    RETURN a + b;
END;
$$;

COMMENT ON FUNCTION demo.fn_add(INTEGER, INTEGER) IS '加法函数';

-- 过程
CREATE OR REPLACE PROCEDURE demo.sp_noop()
    LANGUAGE plpgsql
AS $$
BEGIN
    NULL;
END;
$$;

COMMENT ON PROCEDURE demo.sp_noop() IS '空过程';

-- 触发器函数
CREATE OR REPLACE FUNCTION demo.fn_users_normalize()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    NEW.email := lower(NEW.email);
    RETURN NEW;
END;
$$;

-- 触发器
CREATE TRIGGER trg_users_normalize
    BEFORE INSERT OR UPDATE
    ON demo.users
    FOR EACH ROW
EXECUTE FUNCTION demo.fn_users_normalize();

COMMENT ON TRIGGER trg_users_normalize ON demo.users IS '邮箱规范化触发器';
