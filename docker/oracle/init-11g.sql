WHENEVER SQLERROR CONTINUE

-- Application login: DEMO / Demo2026
-- ORACLE_PASSWORD is the SYSTEM/SYS password and is not the DEMO password.
CREATE USER DEMO IDENTIFIED BY Demo2026
    DEFAULT TABLESPACE USERS
    QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE,
    CREATE PROCEDURE, CREATE TRIGGER TO DEMO;
GRANT EXECUTE ON SYS.DBMS_METADATA TO DEMO;

ALTER SESSION SET CURRENT_SCHEMA = DEMO;

CREATE TABLE DEMO.USERS (
    ID NUMBER(10) CONSTRAINT USERS_PK PRIMARY KEY,
    USERNAME VARCHAR2(100) NOT NULL CONSTRAINT USERS_USERNAME_UK UNIQUE,
    EMAIL VARCHAR2(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE SEQUENCE DEMO.USERS_ID_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE OR REPLACE TRIGGER DEMO.USERS_ID_TRG
BEFORE INSERT ON DEMO.USERS
FOR EACH ROW
WHEN (NEW.ID IS NULL)
BEGIN
    SELECT DEMO.USERS_ID_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
END;
/

CREATE OR REPLACE TRIGGER DEMO.USERS_UPDATED_AT_TRG
BEFORE UPDATE ON DEMO.USERS
FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

CREATE TABLE DEMO.ORDERS (
    ID NUMBER(10) CONSTRAINT ORDERS_PK PRIMARY KEY,
    USER_ID NUMBER(10) NOT NULL,
    ORDER_NO VARCHAR2(32) NOT NULL CONSTRAINT ORDERS_ORDER_NO_UK UNIQUE,
    AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ORDERS_USER_FK FOREIGN KEY (USER_ID) REFERENCES DEMO.USERS(ID)
);

CREATE SEQUENCE DEMO.ORDERS_ID_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE OR REPLACE TRIGGER DEMO.ORDERS_ID_TRG
BEFORE INSERT ON DEMO.ORDERS
FOR EACH ROW
WHEN (NEW.ID IS NULL)
BEGIN
    SELECT DEMO.ORDERS_ID_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
END;
/

CREATE SEQUENCE DEMO.DEMO_SEQ
    START WITH 100
    INCREMENT BY 5
    NOCACHE
    NOCYCLE;

CREATE OR REPLACE VIEW DEMO.V_USERS AS
SELECT ID, USERNAME, EMAIL, CREATED_AT
FROM DEMO.USERS;

CREATE OR REPLACE VIEW DEMO.V_USER_EMAILS AS
SELECT USERNAME, EMAIL
FROM DEMO.USERS;

CREATE OR REPLACE VIEW DEMO.V_ORDERS AS
SELECT ID, USER_ID, ORDER_NO, AMOUNT, CREATED_AT
FROM DEMO.ORDERS;

CREATE OR REPLACE PROCEDURE DEMO.ADD_USER(
    p_username IN VARCHAR2,
    p_email IN VARCHAR2
) AS
BEGIN
    INSERT INTO USERS(USERNAME, EMAIL) VALUES (p_username, p_email);
END;
/

CREATE OR REPLACE FUNCTION DEMO.USER_COUNT
RETURN NUMBER
AS
    result_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO result_count FROM USERS;
    RETURN result_count;
END;
/

COMMENT ON TABLE DEMO.USERS IS 'EasyShell Oracle integration users';
COMMENT ON COLUMN DEMO.USERS.ID IS 'Sequence/trigger generated primary key';

