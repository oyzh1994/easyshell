CREATE OR ALTER VIEW [EASYSHELL_SRC].[V_USERS]
AS
SELECT [ID], [NAME], [EMAIL], [AGE], [ACTIVE], [NAME_UPPER]
FROM [EASYSHELL_SRC].[USERS];
GO

CREATE OR ALTER FUNCTION [EASYSHELL_SRC].[FN_ADD]
(
    @A INT,
    @B INT
)
RETURNS INT
AS
BEGIN
    RETURN @A + @B;
END;
GO

CREATE OR ALTER PROCEDURE [EASYSHELL_SRC].[SP_NOOP]
AS
BEGIN
    SELECT 1 AS [VALUE];
END;
GO

CREATE SEQUENCE [EASYSHELL_SRC].[SEQ_ORDER]
    AS BIGINT
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 999999
    NO CACHE
    CYCLE;
GO

CREATE OR ALTER TRIGGER [EASYSHELL_SRC].[TRG_USERS_NORMALIZE]
ON [EASYSHELL_SRC].[USERS]
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF TRIGGER_NESTLEVEL() > 1
        RETURN;

    UPDATE U
    SET [EMAIL] = LOWER(U.[EMAIL])
    FROM [EASYSHELL_SRC].[USERS] U
    JOIN inserted I ON I.[ID] = U.[ID];
END;
GO

