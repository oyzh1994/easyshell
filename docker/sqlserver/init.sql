CREATE TABLE [EASYSHELL_SRC].[USERS]
(
    [ID] BIGINT IDENTITY(1, 1) NOT NULL,
    [NAME] NVARCHAR(64) NOT NULL,
    [EMAIL] NVARCHAR(255) NULL,
    [AGE] INT NULL,
    [BALANCE] DECIMAL(12, 2) NULL CONSTRAINT [DF_USERS_BALANCE] DEFAULT (0),
    [ACTIVE] BIT NULL CONSTRAINT [DF_USERS_ACTIVE] DEFAULT (1),
    [AVATAR] VARBINARY(MAX) NULL,
    [PROFILE] NVARCHAR(MAX) NULL,
    [CREATED_AT] DATETIME2(7) NULL CONSTRAINT [DF_USERS_CREATED_AT] DEFAULT (SYSUTCDATETIME()),
    [NAME_UPPER] AS (UPPER([NAME])) PERSISTED,
    CONSTRAINT [PK_USERS] PRIMARY KEY ([ID]),
    CONSTRAINT [UQ_USERS_EMAIL] UNIQUE ([EMAIL]),
    CONSTRAINT [CK_USERS_AGE] CHECK ([AGE] >= 0),
    CONSTRAINT [CK_USERS_BALANCE] CHECK ([BALANCE] >= 0),
    CONSTRAINT [CK_USERS_PROFILE_JSON] CHECK ([PROFILE] IS NULL OR ISJSON([PROFILE]) = 1)
);
GO

CREATE INDEX [IX_USERS_NAME] ON [EASYSHELL_SRC].[USERS] ([NAME]);
GO

CREATE TABLE [EASYSHELL_SRC].[ORDERS]
(
    [ID] BIGINT IDENTITY(1, 1) NOT NULL,
    [USER_ID] BIGINT NOT NULL,
    [ORDER_NO] NVARCHAR(64) NOT NULL,
    [AMOUNT] DECIMAL(12, 2) NOT NULL CONSTRAINT [DF_ORDERS_AMOUNT] DEFAULT (0),
    [STATUS] NVARCHAR(16) NOT NULL CONSTRAINT [DF_ORDERS_STATUS] DEFAULT (N'NEW'),
    [CREATED_AT] DATETIME2(7) NULL CONSTRAINT [DF_ORDERS_CREATED_AT] DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT [PK_ORDERS] PRIMARY KEY ([ID]),
    CONSTRAINT [UQ_ORDERS_ORDER_NO] UNIQUE ([ORDER_NO]),
    CONSTRAINT [FK_ORDERS_USERS] FOREIGN KEY ([USER_ID])
        REFERENCES [EASYSHELL_SRC].[USERS] ([ID])
);
GO

CREATE TABLE [EASYSHELL_SRC].[ORDER_ITEMS]
(
    [ID] INT NOT NULL,
    [ORDER_ID] BIGINT NOT NULL,
    [SKU] NVARCHAR(64) NOT NULL,
    [QUANTITY] INT NOT NULL,
    CONSTRAINT [PK_ORDER_ITEMS] PRIMARY KEY ([ID]),
    CONSTRAINT [FK_ORDER_ITEMS_ORDERS] FOREIGN KEY ([ORDER_ID])
        REFERENCES [EASYSHELL_SRC].[ORDERS] ([ID])
);
GO

CREATE TABLE [EASYSHELL_SRC].[COMPLEX_TYPES]
(
    [ID] BIGINT IDENTITY(10, 1) NOT NULL,
